/**
 * Idempotently seeds the master bank catalogue into `institutions` and `institution_bank_profiles`.
 */
export async function seedBankCatalogue() {
  console.log("=== SEEDING BANGLADESH BANK MASTER CATALOGUE ===");
  const stats = {
    total: BANGLADESH_BANK_CATALOGUE.length,
    imported: 0,
    updated: 0,
    skipped: 0,
    rejected: 0,
  };

  const connection = await db.getConnection();
  try {
    await connection.beginTransaction();

    for (const bank of BANGLADESH_BANK_CATALOGUE) {
      if (!bank.institutionCode || !bank.name) {
        console.warn(`[REJECTED] Invalid bank data (missing code or name):`, bank);
        stats.rejected++;
        continue;
      }

      // Check if bank exists by institution_code or name
      const [existing] = await connection.query(
        `SELECT id, institution_code, name, status, partnership_status, directory_status 
         FROM institutions 
         WHERE institution_code = ? OR name = ? 
         LIMIT 1`,
        [bank.institutionCode, bank.name]
      );

      let institutionId;

      if (existing.length > 0) {
        const current = existing[0];
        institutionId = current.id;

        // PRESERVE: status and partnership_status if the bank is already active or a partner!
        // We only update catalogue identity and verified contact fields without overwriting active partner state.
        await connection.execute(
          `
          UPDATE institutions SET
            name = ?,
            name_bn = COALESCE(?, name_bn),
            legal_name = COALESCE(?, legal_name),
            institution_type = ?,
            website_url = COALESCE(website_url, ?),
            support_email = COALESCE(support_email, ?),
            support_phone = COALESCE(support_phone, ?),
            head_office_address = COALESCE(head_office_address, ?),
            division = COALESCE(division, ?),
            district = COALESCE(district, ?),
            upazila = COALESCE(upazila, ?),
            postal_code = COALESCE(postal_code, ?),
            description = COALESCE(description, ?),
            source_name = ?,
            source_url = ?,
            source_checked_at = NOW(),
            source_verified_by = 'Bangladesh Bank Official Directory',
            directory_status = 'verified',
            updated_at = NOW()
          WHERE id = ?
          `,
          [
            bank.name,
            bank.nameBn,
            bank.legalName,
            bank.institutionType,
            bank.websiteUrl,
            bank.supportEmail,
            bank.supportPhone,
            bank.headOfficeAddress,
            bank.division,
            bank.district,
            bank.upazila,
            bank.postalCode,
            bank.description,
            bank.sourceName,
            bank.sourceUrl,
            institutionId,
          ]
        );

        stats.updated++;
      } else {
        // INSERT NEW CATALOGUE RECORD:
        // status = 'draft' (Catalogue entry, not yet registered on BanglaQR platform)
        // partnership_status = 'none' (No active platform partnership yet)
        // directory_status = 'verified' (Verified in Bangladesh Bank directory)
        const [insertResult] = await connection.execute(
          `
          INSERT INTO institutions (
            institution_code, name, name_bn, legal_name, institution_type,
            website_url, support_email, support_phone, head_office_address,
            division, district, upazila, postal_code, description,
            status, directory_status, partnership_status, regulatory_status,
            source_name, source_url, source_checked_at, source_verified_by,
            created_at, updated_at
          ) VALUES (
            ?, ?, ?, ?, ?,
            ?, ?, ?, ?,
            ?, ?, ?, ?, ?,
            'draft', 'verified', 'none', 'scheduled_bank',
            ?, ?, NOW(), 'Bangladesh Bank Official Directory',
            NOW(), NOW()
          )
          `,
          [
            bank.institutionCode,
            bank.name,
            bank.nameBn,
            bank.legalName,
            bank.institutionType,
            bank.websiteUrl,
            bank.supportEmail,
            bank.supportPhone,
            bank.headOfficeAddress,
            bank.division,
            bank.district,
            bank.upazila,
            bank.postalCode,
            bank.description,
            bank.sourceName,
            bank.sourceUrl,
          ]
        );

        institutionId = insertResult.insertId;
        stats.imported++;
      }

      // Upsert into `institution_bank_profiles`
      await connection.execute(
        `
        INSERT INTO institution_bank_profiles (
          institution_id, bank_category, ownership_type, banking_model,
          official_bank_code, swift_code, regulatory_reference,
          created_at, updated_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, NOW(), NOW())
        ON DUPLICATE KEY UPDATE
          bank_category = VALUES(bank_category),
          ownership_type = VALUES(ownership_type),
          banking_model = VALUES(banking_model),
          official_bank_code = COALESCE(official_bank_code, VALUES(official_bank_code)),
          swift_code = COALESCE(swift_code, VALUES(swift_code)),
          regulatory_reference = COALESCE(regulatory_reference, VALUES(regulatory_reference)),
          updated_at = NOW()
        `,
        [
          institutionId,
          bank.bankCategory,
          bank.ownershipType,
          bank.bankingModel,
          bank.officialBankCode,
          bank.swiftCode,
          bank.regulatoryReference,
        ]
      );
    }

    // Also: Ensure existing active banks with branches or gateways have partnership_status = 'active_partner'
    await connection.execute(`
      UPDATE institutions 
      SET partnership_status = 'active_partner' 
      WHERE (id IN (1, 2, 3) OR status = 'active') 
        AND partnership_status = 'none' 
        AND institution_code IN ('PRIME', 'DHAKA_BANK', 'CITY_BANK')
    `);

    await connection.commit();

    console.log("==================================================");
    console.log("BANGLADESH BANK CATALOGUE SEED SUMMARY:");
    console.log(`Total Official Banks in Catalogue : ${stats.total}`);
    console.log(`Imported New Catalogue Entries    : ${stats.imported}`);
    console.log(`Updated Existing Bank Profiles    : ${stats.updated}`);
    console.log(`Skipped / Kept Unchanged          : ${stats.skipped}`);
    console.log(`Rejected Invalid Entries          : ${stats.rejected}`);
    console.log("==================================================");

    return stats;
  } catch (err) {
    await connection.rollback();
    console.error("Failed to seed bank catalogue:", err);
    throw err;
  } finally {
    connection.release();
  }
}

